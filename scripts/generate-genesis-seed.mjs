// Writes docs/supabase-seed-genesis.sql from the two source-of-truth files:
//   data/genesis-codes.json   (permanent codes, printed on the cards)
//   data/genesis-messages.ts  (card wording, in card order)
//
// Safe to re-run: the SQL upserts on `code`, so changing a message here and
// re-applying updates the row without touching codes or recorded moments.
//
//   node scripts/generate-genesis-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { cards } = JSON.parse(readFileSync(join(root, "data/genesis-codes.json"), "utf8"));

// The messages file is a plain array of double-quoted string literals, one
// per line. Read those lines rather than executing TypeScript.
const source = readFileSync(join(root, "data/genesis-messages.ts"), "utf8");
const arrayBody = source.slice(source.indexOf("GENESIS_MESSAGES: readonly string[] = ["));
const messages = arrayBody
  .split("\n")
  .map((line) => line.trim())
  .filter((line) => line.startsWith('"') && line.endsWith('",'))
  .map((line) => JSON.parse(line.slice(0, -1)));

if (cards.length !== 50 || messages.length !== 50) {
  throw new Error(`expected 50 cards and 50 messages, got ${cards.length} and ${messages.length}`);
}

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const rows = cards
  .map((card, i) => `  (${Number(card.number)}, ${q(card.code)}, ${q(messages[i])})`)
  .join(",\n");

const sql = `-- GENERATED by scripts/generate-genesis-seed.mjs — do not edit by hand.
-- The 50 GENESIS ripples: codes from data/genesis-codes.json, wording from
-- data/genesis-messages.ts. Apply after the schema. Re-applying is safe.

insert into public.ripples (number, code, message, batch_id)
select v.number, v.code, v.message, b.id
from (values
${rows}
) as v(number, code, message)
cross join (select id from public.batches where slug = 'genesis') as b
on conflict (code) do update set message = excluded.message;
`;

writeFileSync(join(root, "docs/supabase-seed-genesis.sql"), sql);
console.log(`wrote docs/supabase-seed-genesis.sql (${cards.length} ripples)`);
